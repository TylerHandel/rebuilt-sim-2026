// 4414's launch table, made their way ("For a range of inputs, compute ALL possible shots that
// score in the goal ... Find the shot at each set of inputs that is most robust to errors ...
// Precompute ... to look up hood angle/flywheel speed quickly at runtime", their binder): from the
// sim's own shots (tools/mechlab4414.mjs shooter with MAP=1: how fast, how steep and from where FUEL
// leave at each flywheel speed and hood), smooth fits of the exit speed, elevation and exit point;
// then for each distance from the turret's axis to the HUB's center, every hood that can put a FUEL
// down through the HUB's opening there, and of those the one whose landing moves least with the
// exit speed (the most forgiving of a flywheel off its speed) and comes in steeply enough to drop
// through. Writes js/mech/shot4414.js. Run:
//   node --import ./tools/node-env.mjs tools/mechlab4414.mjs shooter   (MAP=1, first)
//   node --import ./tools/node-env.mjs tools/shot4414.mjs
import { readFileSync, writeFileSync } from 'fs';
import { sim2D } from '../js/ballistics.js';
import { HUB } from '../js/constants.js';
import { SHOOTER } from '../js/mech/r4414.js';

const map = JSON.parse(readFileSync('tools/shot4414-map.json', 'utf8')).filter((m) => m.n >= 2);
// least squares: y ~ sum c_k f_k(x)
function fit(rows, feats, key) {
  const n = feats(rows[0]).length, A = Array.from({ length: n }, () => new Array(n).fill(0)), b = new Array(n).fill(0);
  for (const r of rows) { const f = feats(r); for (let i = 0; i < n; i++) { b[i] += f[i] * r[key]; for (let j = 0; j < n; j++) A[i][j] += f[i] * f[j]; } }
  // (Gauss-Jordan)
  for (let i = 0; i < n; i++) {
    let p = i; for (let k = i + 1; k < n; k++) if (Math.abs(A[k][i]) > Math.abs(A[p][i])) p = k;
    [A[i], A[p]] = [A[p], A[i]]; [b[i], b[p]] = [b[p], b[i]];
    for (let k = 0; k < n; k++) if (k !== i) { const q = A[k][i] / A[i][i]; for (let j = i; j < n; j++) A[k][j] -= q * A[i][j]; b[k] -= q * b[i]; }
  }
  return b.map((v, i) => v / A[i][i]);
}
// features: r = rad / 100, h = (hood - 140) / 10
const F = (m) => { const r = m.rad / 100, h = (m.hood - 140) / 10; return [1, r, r * r, r * r * r, h, h * r, h * h]; };
const C = { v: fit(map, F, 'v'), el: fit(map, F, 'el'), x: fit(map, F, 'x'), y: fit(map, F, 'y') };
const ev = (c, rad, hood) => F({ rad, hood }).reduce((a, f, i) => a + f * c[i], 0);
const rms = (k) => Math.sqrt(map.reduce((a, m) => a + (ev(C[k], m.rad, m.hood) - m[k]) ** 2, 0) / map.length);
console.log(`fits over ${map.length} map points: exit speed rms ${rms('v').toFixed(2)} m/s, elevation ${rms('el').toFixed(1)} deg, exit point ${rms('x').toFixed(3)}, ${rms('y').toFixed(3)} m`);

const D2R = Math.PI / 180;
// where a shot at (rad, hood) comes down through the HUB's opening height, from the turret's axis
function land(rad, hood) {
  const v = ev(C.v, rad, hood), el = ev(C.el, rad, hood), x = ev(C.x, rad, hood), y = ev(C.y, rad, hood);
  const hit = sim2D(y, v, el * D2R, HUB.rimFront);
  return hit ? { d: x + hit.d, alpha: hit.alpha / D2R, v, el } : null;
}
const RAD = [200, 700], HEADROOM = 5;
const rows = [];
for (let d = 1.0; d <= 7.01; d += 0.1) {
  let best = null;
  // (5 deg of the hood's travel kept in hand each way: shooting on the move, the robot's own motion
  // can call for a shot a little steeper or flatter than the table's)
  for (let hood = SHOOTER.hoodMin + HEADROOM; hood <= SHOOTER.hoodMax - HEADROOM; hood += 0.5) {
    // the flywheel speed that lands it at d (bisection; landing grows with speed over the map)
    let lo = RAD[0], hi = RAD[1];
    const L = (r) => land(r, hood)?.d ?? -1;
    if (L(lo) > d || L(hi) < d) continue;
    for (let k = 0; k < 40; k++) { const m = (lo + hi) / 2; if (L(m) < d) lo = m; else hi = m; }
    const rad = (lo + hi) / 2, s = land(rad, hood);
    if (!s || Math.abs(s.d - d) > 0.02) continue;
    // how far the landing moves for a 0.1 m/s miss in exit speed (via the flywheel), and how steep
    // it comes down (the opening's back edge is 8in higher than its front: under ~40 deg it rims out)
    const dr = 2, dv = ev(C.v, rad + dr, hood) - ev(C.v, rad - dr, hood), dd = L(rad + dr) - L(rad - dr);
    const sens = Math.abs(dd / (dv || 1e-6)) * 0.1;
    const score = sens + (s.alpha < 45 ? (45 - s.alpha) * 0.02 : 0);
    if (!best || score < best.score) best = { d, rad, hood, v: s.v, el: s.el, alpha: s.alpha, sens, score };
  }
  if (best) rows.push(best);
}
for (const r of rows.filter((_, i) => i % 5 === 0)) console.log(`  ${r.d.toFixed(1)} m: ${r.rad.toFixed(0)} rad/s, hood ${r.hood.toFixed(1)} -> ${r.v.toFixed(2)} m/s at ${r.el.toFixed(1)} deg, coming down at ${r.alpha.toFixed(0)} deg; ${r.sens.toFixed(2)} m per 0.1 m/s`);
const r3 = (x) => Math.round(x * 1000) / 1000;
writeFileSync('js/mech/shot4414.js', `// 4414's launch table and the fits it's made from (generated by tools/shot4414.mjs from the sim's
// own shots, tools/mechlab4414.mjs shooter MAP=1; see js/mech/r4414.js). FIT: exit speed (m/s),
// elevation (deg) and exit point (m out from the turret's axis, m up) against the flywheel's speed
// and the hood, as sums of the features [1, r, r^2, r^3, h, h r, h^2], r = rad/s / 100,
// h = (hood deg - 140) / 10. LAUNCH: distance from the turret's axis to the HUB's center (m) ->
// flywheel rad/s, hood deg, exit speed m/s, elevation deg.
export const FIT = ${JSON.stringify({ v: C.v.map((x) => +x.toPrecision(6)), el: C.el.map((x) => +x.toPrecision(6)), x: C.x.map((x) => +x.toPrecision(6)), y: C.y.map((x) => +x.toPrecision(6)) })};
export const LAUNCH = ${JSON.stringify(rows.map((r) => [r3(r.d), Math.round(r.rad), r3(r.hood), r3(r.v), r3(r.el)]))};
`);
console.log(`wrote js/mech/shot4414.js: ${rows.length} rows, ${rows[0]?.d.toFixed(1)} to ${rows[rows.length - 1]?.d.toFixed(1)} m`);
